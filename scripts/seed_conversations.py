def main() -> int:
    print_header("灌入历史客服对话种子数据")
    session_factory = session_factory_from(load_settings())
    created_conversations = 0
    created_messages = 0
    with session_factory() as session:
        for suffix, rounds in SEED_CONVERSATIONS:
            conversation_id = f"00000000-0000-4000-8000-{int(suffix):012d}"
            # 幂等：固定 ID + 已有消息即跳过，重复运行不翻倍
            conversation = session.get(Conversation, conversation_id)
            if conversation is None:
                conversation = Conversation(id=conversation_id, user_id="seed-user", status="closed")
                session.add(conversation)
                session.flush()
            message_count = session.scalar(
                select(func.count()).select_from(Message).where(Message.conversation_id == conversation_id)
            )
            if message_count:
                continue
            for user_text, assistant_text in rounds:
                append_message(session, conversation_id, role="user", content=user_text)
                append_message(session, conversation_id, role="assistant", content=assistant_text)
                created_messages += 2
            created_conversations += 1
        session.commit()
    print(f"新增会话 {created_conversations} 个，新增消息 {created_messages} 条（已存在的会话自动跳过）")
    print("下一步：uv run python -m scripts.kb_mine")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
